// Builds the /partners page bundle.
//
//   PARTNERS_CODE=MONA-XXXXX-XXXXX node scripts/partners-encrypt.mjs
//
// Reads the pitch from partners-src/pitch.html (git-ignored: this repo is
// public, so the plain pitch must never be committed) and the login page from
// lib/partners/login.html, puts the logo into both, encrypts the pitch with a
// key derived from the access code (scrypt + AES-256-GCM) and writes
// lib/partners/pages.generated.ts. Only someone with the code can decrypt it,
// on the server or from GitHub. Changing the code = run this again with the
// new code; the old code then stops working.

import { randomBytes, scryptSync, createCipheriv } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const code = (process.env.PARTNERS_CODE ?? "").trim().toUpperCase();
if (code.length < 12) {
  console.error("Set PARTNERS_CODE (at least 12 characters).");
  process.exit(1);
}

const logo = readFileSync(join(root, "lib/partners/logo.html"), "utf8").trim();
const fill = (html) => html.split("<!--LOGO-->").join(logo);
const pitch = fill(readFileSync(join(root, "partners-src/pitch.html"), "utf8"));
const login = fill(readFileSync(join(root, "lib/partners/login.html"), "utf8"));

const salt = randomBytes(16);
const iv = randomBytes(12);
const key = scryptSync(code, salt, 32, { N: 32768, r: 8, p: 1, maxmem: 64 * 1024 * 1024 });
const cipher = createCipheriv("aes-256-gcm", key, iv);
const data = Buffer.concat([cipher.update(pitch, "utf8"), cipher.final()]);
const tag = cipher.getAuthTag();

const out = `// Generated by scripts/partners-encrypt.mjs — do not edit by hand.
// The pitch is encrypted; see that script for how to change it.

export const LOGIN_HTML = ${JSON.stringify(login)};

export const PITCH = {
  salt: "${salt.toString("base64")}",
  iv: "${iv.toString("base64")}",
  tag: "${tag.toString("base64")}",
  data: "${data.toString("base64")}",
} as const;
`;
writeFileSync(join(root, "lib/partners/pages.generated.ts"), out);
console.log(`Wrote lib/partners/pages.generated.ts (pitch ${pitch.length} chars, encrypted).`);
